"""Compact, deterministic digest of lane-plan.json for the Act scheduler.

Relaying the whole lane-plan.json through a datum-cli runner is not viable:
an LLM echo normalised "§4" to "§ 4" inside acceptance criteria (changing
spec hashes, elonchesd run wf_6bfbd9f2-510), and the base64 chunk relay
that replaced it was GENERATED by the runner past ~2.7 KB rather than
copied (wf_5791e11f-693). The scheduler only needs topology, files and a
per-lane spec hash — a few KB a runner echoes reliably, byte-checked by the
batch (wc -c + git hash-object of the written digest). Everything else
about a lane (acceptance criteria, notes) is fetched per lane at intake,
straight from the file in the lane's worktree.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

from datum.lane_hash import lane_spec_hash

SCHEMA_VERSION = 1

# Lane fields the scheduler and the lane runner read in-script. Anything not
# listed (acceptance_criteria, red_note, stage, description, ...) stays in
# the file and is fetched per lane at intake.
_LANE_FIELDS = (
    "title",
    "files",
    "reads",
    "depends_on",
    "kind",
    "github_issue",
    "test_command",
    "expect_tests_pass",
    "invariants",
)


class DigestError(ValueError):
    """The plan could not be digested; the message is safe to print as JSON."""


def build_digest(plan: dict, lane_plan_sha: str) -> dict:
    """Pure: the digest dict for a parsed lane plan."""
    lanes = plan.get("lanes")
    if not isinstance(lanes, dict) or not lanes:
        raise DigestError("lane plan has no lanes object")
    order = plan.get("topological_order")
    if not isinstance(order, list):
        raise DigestError("lane plan has no topological_order list")
    digest_lanes: dict[str, dict] = {}
    for lane_id in sorted(lanes):
        lane = lanes[lane_id]
        if not isinstance(lane, dict):
            raise DigestError(f"lane {lane_id!r} is not an object")
        entry: dict = {}
        for field in _LANE_FIELDS:
            if field in lane and lane[field] is not None:
                entry[field] = lane[field]
        entry.setdefault("files", [])
        entry.setdefault("reads", [])
        entry.setdefault("depends_on", [])
        entry["spec_hash"] = lane_spec_hash(lane)
        digest_lanes[lane_id] = entry
    return {
        "schema_version": SCHEMA_VERSION,
        "lane_plan_sha": lane_plan_sha,
        "total_lanes": int(plan.get("total_lanes") or len(lanes)),
        "topological_order": list(order),
        "lanes": digest_lanes,
    }


def dumps_digest(digest: dict) -> str:
    """One compact line plus a trailing newline — the exact bytes `--out` writes."""
    return (
        json.dumps(digest, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
        + "\n"
    )


def check_integration_lanes_scheduled(plan: dict, plan_path: Path) -> None:
    """Every invariant in the epic's PROPERTIES.md has an integration lane.

    Properties schedules integration lanes (`datum lane-plan --properties`)
    only after its gate passes inside the workflow. A gate fixed and passed
    by hand, then `datum go --start-from act`, skipped that step and Act ran
    a plan without them (self-hosted run 20261012: 19 invariant lanes never
    built, nothing said so). Every Act start digests the plan, so the check
    lives here and fails closed with the scheduling command.
    """
    properties = plan_path.parent / "PROPERTIES.md"
    if not properties.is_file():
        return
    from datum.integration_invariants import (
        IntegrationInvariantError,
        parse_integration_invariants,
    )

    try:
        invariants = parse_integration_invariants(
            properties.read_text(encoding="utf-8")
        )
    except IntegrationInvariantError as exc:
        raise DigestError(
            f"integration_invariants_malformed: {properties}: {exc}"
        ) from exc
    if not invariants:
        return
    scheduled: set[str] = set()
    for lane in (plan.get("lanes") or {}).values():
        if isinstance(lane, dict) and lane.get("kind") == "integration":
            scheduled.update(str(i) for i in lane.get("invariants") or [])
    missing = [inv["id"] for inv in invariants if inv["id"] not in scheduled]
    if not missing:
        return
    epic = plan_path.parent
    raise DigestError(
        f"integration_lanes_unscheduled: {', '.join(missing)} in {properties} "
        f"have no integration lane in {plan_path} — schedule them with "
        f"`datum lane-plan --input {epic}/tasks.json --output {plan_path} "
        f"--md-output {epic}/TASKS.md --properties {properties}`, commit "
        f"lane-plan.json and TASKS.md, run `datum gate plan`, then "
        f"`datum go --start-from act`"
    )


def digest_plan_file(plan_path: Path) -> str:
    if not plan_path.is_file():
        raise DigestError(f"lane plan not found: {plan_path}")
    try:
        plan = json.loads(plan_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise DigestError(f"lane plan is not valid JSON: {plan_path}: {exc}") from exc
    sha = subprocess.run(
        ["git", "hash-object", str(plan_path)],
        capture_output=True,
        text=True,
        check=False,
    )
    if sha.returncode != 0:
        raise DigestError(
            f"git hash-object failed for {plan_path}: {sha.stderr.strip()}"
        )
    digest = build_digest(plan, sha.stdout.strip())
    check_integration_lanes_scheduled(plan, plan_path)
    return dumps_digest(digest)
